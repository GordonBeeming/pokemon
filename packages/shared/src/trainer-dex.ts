export function trainerCharacterKey(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}
export function normalizedTrainerName(name: string): string {
  return name.trim().replace(/’/g, "'").replace(/\./g, '').toLowerCase();
}
export const TRAINER_CHARACTERS: readonly TrainerCharacter[] = TRAINER_REGIONS.flatMap((region) =>
  regionalNames[region].map((name) => {
    const key = trainerCharacterKey(name);
    return {
      key,
      name,
      regions: [region, ...(additionalRegions[key] ?? [])],
      aliases: [name, ...(aliases[key] ?? [])].map(normalizedTrainerName),
      cardIds: cardIdentities[key] ?? [],
    };
  }),
);
export const trainerDexEntrySchema = z.object({
  key: z.string(),
  name: z.string(),
  regions: z.array(z.enum(TRAINER_REGIONS)),
  cardCount: z.number().int().nonnegative(),
  ownedCount: z.number().int().nonnegative(),
  representative: z
    .object({
      id: z.string(),
      name: z.string(),
      number: z.string(),
      setName: z.string(),
      imageLowUrl: z.string().nullable(),
      owned: z.boolean(),
    })
    .nullable(),
});
export const trainerDexResponseSchema = z.object({ trainers: z.array(trainerDexEntrySchema) });
export type TrainerDexEntry = z.infer<typeof trainerDexEntrySchema>;
